_KANA_RE = re.compile(r"[\u3040-\u30FF]")
_CJK_RE = re.compile(r"[\u3400-\u9FFF]")

# 推導檔名時要拿掉的公司後綴
_DROP_WORDS = {"co", "ltd", "inc", "corp", "corporation", "company", "holdings",
               "holding", "group", "kk", "the", "and", "limited", "plc", "sa", "ag"}


def normalize_code(raw):
    """統一成 Yahoo／JPX 的日股格式（4 碼 + .T）。"""
    c = str(raw or "").strip().upper().replace(" ", "")
    if not c:
        return ""
    if re.fullmatch(r"\d{3}[0-9A-Z]", c):
        return c + ".T"
    return re.sub(r"\.(JP|JPN|TO|TYO|TSE)$", ".T", c)


def code_digits(code):
    m = re.match(r"^(\d{3}[0-9A-Z])", str(code or "").upper())
    return m.group(1) if m else ""


def to_traditional(text):
    return "".join(KANJI_MAP.get(ch, ch) for ch in str(text or ""))


def _clean_ja(name):
    t = str(name or "")
    t = t.replace("株式会社", "").replace("(株)", "").replace("（株）", "")
    t = re.sub(r",?\s*(Inc|Ltd|Corp|Corporation|Co)\.?,?$", "", t, flags=re.I).strip()
    for a, b in KANA_TERMS:
        t = t.replace(a, b)
    t = t.replace("の", "之")          # 味の素 → 味之素
    return to_traditional(t).strip()


def _kana_ratio(s):
    t = re.sub(r"\s", "", str(s or ""))
    if not t:
        return 1.0
    return len(_KANA_RE.findall(t)) / len(t)


def pick_name(names, code=""):
    """挑一個最適合的顯示名稱：慣用譯名 > 漢字（轉繁體） > 英文。"""
    known = CN_NAMES.get(code_digits(code))
    if known:
        return known
    names = [n for n in (names or []) if n]
    if not names:
        return ""
    en = next((n for n in names if not _CJK_RE.search(n) and re.search(r"[A-Za-z]", n)), None)
    ja = next((n for n in names if re.search(r"[\u3040-\u9FFF]", n)), None)
    if ja:
        cleaned = _clean_ja(ja)
        if cleaned and _kana_ratio(cleaned) <= 0.3:
            return cleaned
    return en or (_clean_ja(ja) if ja else names[0])


def suggest_key(names, code):
    """從英文名推一個好記的檔名代號，例如 Shin-Etsu Chemical → shinetsu。"""
    for n in (names or []):
        if not n or not re.search(r"[A-Za-z]", n):
            continue
        words = [w.lower() for w in re.split(r"[^A-Za-z0-9]+", n) if w]
        words = [w for w in words if w not in _DROP_WORDS]
        if words:
            key = "".join(words[:2])[:24]
            if key:
                return key
    return "s" + str(code).replace(".", "").lower()
